const LEGACY_TOOL_ENTITY_KEY: Record<string, string> = {
  "crm.list_leads": "lead",
  "crm.get_lead": "lead",
  "crm.create_lead": "lead",
  "crm.update_lead_status": "lead",
  "crm.list_opportunities": "opportunity",
  "crm.create_opportunity": "opportunity",
  "crm.list_customers": "customer",
};
export function resolveEntityKey(toolName: string | undefined): string | undefined {
  if (!toolName) return undefined;
  return LEGACY_TOOL_ENTITY_KEY[toolName] ?? toolName.split(".")[0];
}

/** Identifies one exact tool call (name + arguments) within a single turn,
 *  used by the run() loop's seenCallResults dedup cache (see its own doc
 *  comment) — pulled out as its own pure function purely so the "what
 *  counts as an exact repeat" logic is directly unit-testable without
 *  standing up the full run() loop. Argument key order doesn't matter for
 *  what the model actually asked for ({a:1,b:2} and {b:2,a:1} are the same
 *  call) — JSON.stringify alone would treat those as different keys since
 *  it preserves insertion order, so keys are sorted first. */
export function buildToolCallKey(name: string, args: any): string {
  const normalized = args && typeof args === "object" && !Array.isArray(args)
    ? Object.keys(args).sort().reduce((acc, k) => { acc[k] = args[k]; return acc; }, {} as Record<string, any>)
    : args ?? {};
  return `${name}::${JSON.stringify(normalized)}`;
}


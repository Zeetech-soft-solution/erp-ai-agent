/** Shared HTML-escaping so every renderer stays safe against tool data
 *  that may contain untrusted strings (customer names, email bodies...). */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
